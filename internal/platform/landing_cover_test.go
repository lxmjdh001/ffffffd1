func TestLandingCoverQueuedOnSaveServesRealPNGWithoutBusinessEffects(t *testing.T) {
	s := meteredServer(t, 0)
	admin, owner := landingLibraryAdmin(t, s), seedUser(t, s, Dollar)
	data := landingCoverTestPNG(t)
	var captured LandingCoverRenderInput
	s.landingCoverCapture = func(_ context.Context, in LandingCoverRenderInput) ([]byte, error) {
		captured = in
		return data, nil
	}
	source := createLandingLibraryFixture(t, s, admin, "Screenshot source")
	if source.CoverStatus != "pending" || source.CoverURL != "" || len(source.CoverHash) != 64 || countRows(t, s, &LandingCover{}) != 1 {
		t.Fatal("template save did not queue its generated cover")
	}
	url := "/api/landing-template-covers/" + source.CoverHash + ".png"
	requireCode(t, pushTaskCall(t, s, "GET", url, nil, owner, "", "correct"), 503)
	landingCoverTestWork(t, s)
	if captured.HTML != source.HTML || captured.Name != source.Name || captured.Mode != "pwa" || !diySupports(captured.Config, "apk") {
		t.Fatalf("screenshot was not taken from the source snapshot: %+v", captured)
	}
	job := landingCoverTestJob(t, s, source.CoverHash)
	if job.State != "ready" || job.Attempts != 1 || !bytes.Equal(job.PNG, data) || job.LeaseUntil != nil {
		t.Fatal("generated bytes were not persisted as an immutable ready cover")
	}
	requireCode(t, call(t, s, "GET", url, nil, nil, ""), 401)
	w := pushTaskCall(t, s, "GET", url, nil, owner, "", "correct")
	requireCode(t, w, 200)
	if w.Header().Get("Content-Type") != "image/png" || !bytes.Equal(w.Body.Bytes(), data) || !strings.Contains(w.Header().Get("Cache-Control"), "private") {
		t.Fatal("cover endpoint did not return the real privately cached PNG")
	}
	cookie, _ := sessionFor(t, s, owner)
	r := httptest.NewRequest("GET", s.Config.PublicURL+url, nil)
	r.AddCookie(cookie)
	r.Header.Set("If-None-Match", w.Header().Get("ETag"))
	w = httptest.NewRecorder()
	s.Handler().ServeHTTP(w, r)
	requireCode(t, w, 304)
	if w.Body.Len() != 0 {
		t.Fatal("conditional cover GET returned image bytes")
	}
	for _, reader := range []struct {
		user User
		path string
	}{{owner, "/api/landing-templates"}, {admin, "/api/admin/landing-templates"}} {
		w = pushTaskCall(t, s, "GET", reader.path, nil, reader.user, "", "correct")
		requireCode(t, w, 200)
		var list struct{ Data []landingLibrarySummary }
		if err := json.Unmarshal(w.Body.Bytes(), &list); err != nil || len(list.Data) != 1 || list.Data[0].CoverURL != url || list.Data[0].CoverStatus != "ready" {
			t.Fatalf("catalog did not project the real cover: %s", w.Body.String())
		}
	}
	favoriteLandingLibraryFixture(t, s, owner, source.ID)
	w = pushTaskCall(t, s, "GET", "/api/landing-favorites", nil, owner, "", "correct")
	var favorites struct{ Data []landingFavoriteView }
	if err := json.Unmarshal(w.Body.Bytes(), &favorites); err != nil || len(favorites.Data) != 1 || favorites.Data[0].CoverURL != url || favorites.Data[0].CoverStatus != "ready" {
		t.Fatal("favorite did not inherit its immutable cover")
	}
	if countRows(t, s, &AccessVisit{}) != 0 || countRows(t, s, &MeteredEvent{}) != 0 || countRows(t, s, &Ledger{}) != 0 || countRows(t, s, &Download{}) != 0 || countRows(t, s, &Ticket{}) != 0 {
		t.Fatal("cover generation or viewing entered the application's business path")
	}
	if current := usageOwner(t, s, owner.ID); current.BalanceMicros != Dollar {
		t.Fatal("a catalog screenshot charged the customer")
	}
}

func TestLandingCoverContentDeduplicationAndConcurrentWorkers(t *testing.T) {
	s := testServer(t)
	admin := landingLibraryAdmin(t, s)
	first := createLandingLibraryFixture(t, s, admin, "Same source")
	second := createLandingLibraryFixture(t, s, admin, "Same source")
	if first.CoverHash != second.CoverHash || countRows(t, s, &LandingCover{}) != 1 {
		t.Fatal("identical rendering inputs did not share the durable job")
	}
	data := landingCoverTestPNG(t)
	var calls atomic.Int64
	started, release := make(chan struct{}), make(chan struct{})
	s.landingCoverCapture = func(context.Context, LandingCoverRenderInput) ([]byte, error) {
		if calls.Add(1) == 1 {
			close(started)
		}
		<-release
		return data, nil
	}
	var wg sync.WaitGroup
	errors := make(chan error, 8)
	wg.Add(1)
	go func() { defer wg.Done(); _, err := s.processLandingCoverJob(context.Background()); errors <- err }()
	<-started
	for range 7 {
		wg.Add(1)
		go func() { defer wg.Done(); _, err := s.processLandingCoverJob(context.Background()); errors <- err }()
	}
	// Wait until other replicas have inspected the active lease, then finish it.
	for i := 0; i < 7; i++ {
		if err := <-errors; err != nil {
			t.Fatal(err)
		}
	}
	close(release)
	wg.Wait()
	if err := <-errors; err != nil {
		t.Fatal(err)
	}
	if calls.Load() != 1 || landingCoverTestJob(t, s, first.CoverHash).State != "ready" {
		t.Fatal("concurrent workers captured the same active job more than once")
	}
	input := landingLibraryTestInput(first.Name)
	input["description"] = "Changed metadata only"
	input["enabled"] = false
	w := pushTaskCall(t, s, "PUT", "/api/admin/landing-templates/"+first.ID, input, admin, "", "correct")
	requireCode(t, w, 200)
	var updated LandingLibraryTemplate
	_ = json.Unmarshal(w.Body.Bytes(), &updated)
	if updated.Version != 2 || updated.CoverHash != first.CoverHash || countRows(t, s, &LandingCover{}) != 1 {
		t.Fatal("publishing metadata unnecessarily invalidated the screenshot")
	}
	input["name"] = "New rendered app name"
	w = pushTaskCall(t, s, "PUT", "/api/admin/landing-templates/"+first.ID, input, admin, "", "correct")
	requireCode(t, w, 200)
	_ = json.Unmarshal(w.Body.Bytes(), &updated)
	if updated.CoverHash == first.CoverHash || updated.CoverStatus != "pending" {
		t.Fatal("rendered app name was omitted from the content hash")
	}
}

func TestLandingCoverRetriesAreBoundedAndRecoverExpiredLeases(t *testing.T) {
	s := testServer(t)
	admin, owner := landingLibraryAdmin(t, s), seedUser(t, s, 0)
	source := createLandingLibraryFixture(t, s, admin, "Retry source")
	// PostgreSQL persists timestamps at microsecond precision. Keep this test
	// clock at the same precision so exact backoff comparisons work on both DBs.
	clock := s.Now().Truncate(time.Microsecond)
	s.Now = func() time.Time { return clock }
	s.landingCoverCapture = func(context.Context, LandingCoverRenderInput) ([]byte, error) {
		return nil, errors.New("internal browser path and source details must remain private")
	}
	for attempt := 1; attempt <= 3; attempt++ {
		landingCoverTestWork(t, s)
		job := landingCoverTestJob(t, s, source.CoverHash)
		if job.Attempts != attempt || strings.Contains(job.LastError, "internal") {
			t.Fatal("retry count or public error redaction failed")
		}
		if attempt < 3 {
			if job.State != "pending" || job.NextAttemptAt.Sub(clock) != time.Duration(attempt*attempt)*10*time.Second {
				t.Fatal("failed cover did not back off")
			}
			worked, err := s.processLandingCoverJob(context.Background())
			if worked || err != nil {
				t.Fatal("worker ignored its retry delay")
			}
			clock = job.NextAttemptAt
		} else if job.State != "failed" {
			t.Fatal("cover did not stop after three attempts")
		}
	}
	path := "/api/admin/landing-templates/" + source.ID + "/cover/retry"
	requireCode(t, pushTaskCall(t, s, "POST", path, map[string]any{}, owner, "", "correct"), 403)
	requireCode(t, pushTaskCall(t, s, "POST", path, map[string]any{}, admin, "", ""), 403)
	requireCode(t, pushTaskCall(t, s, "POST", path, map[string]any{}, admin, "", "correct"), 200)
	job := landingCoverTestJob(t, s, source.CoverHash)
	if job.Attempts != 0 || job.State != "pending" {
		t.Fatal("administrator could not reset failed cover generation")
	}
	claimed, err := s.claimLandingCover(context.Background())
	if err != nil || claimed == nil {
		t.Fatal("failed to claim reset job", err)
	}
	clock = clock.Add(landingCoverLease + time.Second)
	data := landingCoverTestPNG(t)
	s.landingCoverCapture = func(context.Context, LandingCoverRenderInput) ([]byte, error) { return data, nil }
	landingCoverTestWork(t, s)
	if job = landingCoverTestJob(t, s, source.CoverHash); job.State != "ready" || job.Attempts != 2 {
		t.Fatal("expired lease did not recover its persisted job")
	}
	late := s.DB.Model(&LandingCover{}).Where("hash = ? AND state = ? AND lease_id = ?", claimed.Hash, "processing", claimed.LeaseID).Update("state", "failed")
	if late.Error != nil || late.RowsAffected != 0 {
		t.Fatal("an expired worker could still overwrite the new worker")
	}
	if err := s.DB.Model(&LandingCover{}).Where("hash = ?", source.CoverHash).Updates(map[string]any{"state": "processing", "attempts": 3, "lease_id": "abandoned", "lease_until": clock.Add(-time.Second)}).Error; err != nil {
		t.Fatal(err)
	}
	worked, err := s.processLandingCoverJob(context.Background())
	if err != nil || worked || landingCoverTestJob(t, s, source.CoverHash).State != "failed" {
		t.Fatal("a crashed third attempt remained processing indefinitely")
	}
}

func TestLandingCoverAdministratorSaveRetriesFailedContent(t *testing.T) {
	for _, method := range []string{"POST", "PUT"} {
		t.Run(method, func(t *testing.T) {
			s := testServer(t)
			admin, owner := landingLibraryAdmin(t, s), seedUser(t, s, 0)
			source := createLandingLibraryFixture(t, s, admin, "Repaired browser")
			clock := s.Now().Add(time.Minute).Truncate(time.Microsecond)
			s.Now = func() time.Time { return clock }
			if err := s.DB.Model(&LandingCover{}).Where("hash = ?", source.CoverHash).Updates(map[string]any{"state": "failed", "attempts": 3, "next_attempt_at": clock.Add(time.Hour), "last_error": "封面生成失败，请管理员重试", "lease_id": "old-worker", "lease_until": clock.Add(-time.Second)}).Error; err != nil {
				t.Fatal(err)
			}
			// A customer collecting the content cannot repeatedly reset the
			// administrator's exhausted browser job.
			favoriteLandingLibraryFixture(t, s, owner, source.ID)
			if job := landingCoverTestJob(t, s, source.CoverHash); job.State != "failed" || job.Attempts != 3 {
				t.Fatal("favorite reset a failed cover's retry budget")
			}
			path := "/api/admin/landing-templates"
			code := 201
			if method == "PUT" {
				path += "/" + source.ID
				code = 200
				stale := landingLibraryTestInput(source.Name)
				stale["expected_version"] = 999
				requireCode(t, pushTaskCall(t, s, method, path, stale, admin, "", "correct"), 409)
				if landingCoverTestJob(t, s, source.CoverHash).State != "failed" {
					t.Fatal("rejected save reset a failed cover")
				}
			}
			w := pushTaskCall(t, s, method, path, landingLibraryTestInput(source.Name), admin, "", "correct")
			requireCode(t, w, code)
			var saved LandingLibraryTemplate
			if err := json.Unmarshal(w.Body.Bytes(), &saved); err != nil {
				t.Fatal(err)
			}
			job := landingCoverTestJob(t, s, source.CoverHash)
			if saved.CoverHash != source.CoverHash || saved.CoverStatus != "pending" || job.State != "pending" || job.Attempts != 0 || job.LastError != "" || job.LeaseID != "" || job.LeaseUntil != nil || !job.NextAttemptAt.Equal(clock) {
				t.Fatal("administrator save did not automatically requeue the failed content")
			}
			data := landingCoverTestPNG(t)
			var captures int
			s.landingCoverCapture = func(context.Context, LandingCoverRenderInput) ([]byte, error) { captures++; return data, nil }
			landingCoverTestWork(t, s)
			job = landingCoverTestJob(t, s, source.CoverHash)
			if captures != 1 || job.State != "ready" || job.Attempts != 1 || !bytes.Equal(job.PNG, data) {
				t.Fatal("repaired runtime did not regenerate the saved template automatically")
			}
		})
	}
}

