func TestLandingCoverBackgroundWorkerStartsAndStopsIndependently(t *testing.T) {
	s := testServer(t)
	admin := landingLibraryAdmin(t, s)
	source := createLandingLibraryFixture(t, s, admin, "Background cover")
	data := landingCoverTestPNG(t)
	rendered := make(chan struct{})
	s.landingCoverCapture = func(ctx context.Context, _ LandingCoverRenderInput) ([]byte, error) {
		deadline, ok := ctx.Deadline()
		if !ok || time.Until(deadline) > 31*time.Second || time.Until(deadline) < 28*time.Second {
			return nil, errors.New("worker omitted the configured render deadline")
		}
		close(rendered)
		return data, nil
	}
	ctx, cancel := context.WithCancel(context.Background())
	done := make(chan struct{})
	go func() { s.RunLandingCoverWorker(ctx); close(done) }()
	t.Cleanup(func() { cancel(); <-done })
	select {
	case <-rendered:
	case <-time.After(3 * time.Second):
		t.Fatal("independent worker did not render the saved template")
	}
	deadline := time.Now().Add(3 * time.Second)
	for landingCoverTestJob(t, s, source.CoverHash).State != "ready" {
		if time.Now().After(deadline) {
			t.Fatal("background worker did not commit its screenshot")
		}
		time.Sleep(time.Millisecond)
	}
	cancel()
	select {
	case <-done:
	case <-time.After(time.Second):
		t.Fatal("background cover worker did not stop after cancellation")
	}
	if countRows(t, s, &Ledger{}) != 0 || countRows(t, s, &Ticket{}) != 0 || countRows(t, s, &MeteredEvent{}) != 0 {
		t.Fatal("independent cover worker invoked financial maintenance")
	}
}
