func TestLandingCoverMigrationBatchesAndRollsBackAtomically(t *testing.T) {
	s := testServer(t)
	admin := landingLibraryAdmin(t, s)
	owners := []User{seedUser(t, s, Dollar), seedUser(t, s, Dollar)}
	expected := make(map[string]string)
	for i := range 51 {
		source := createLandingLibraryFixture(t, s, admin, fmt.Sprintf("Batched source %03d", i))
		for j, owner := range owners {
			if i == 50 && j == 1 {
				continue
			}
			ref := favoriteLandingLibraryFixture(t, s, owner, source.ID)
			expected[ref.RevisionID] = source.CoverHash
		}
	}
	if err := s.DB.Transaction(func(tx *gorm.DB) error {
		for _, model := range []any{&LandingCoverSnapshot{}, &LandingCover{}} {
			if err := tx.Session(&gorm.Session{AllowGlobalUpdate: true}).Delete(model).Error; err != nil {
				return err
			}
		}
		for _, model := range []any{&LandingLibraryTemplate{}, &LandingLibraryFavorite{}} {
			if err := tx.Model(model).Where("1 = 1").UpdateColumn("cover_hash", "").Error; err != nil {
				return err
			}
		}
		return tx.Delete(&Migration{}, "version = ?", landingCoverMigrationVersion).Error
	}); err != nil {
		t.Fatal(err)
	}
	var sourceBatches, favoriteBatches []int64
	const observe = "test:landing-cover-migration-batches"
	if err := s.DB.Callback().Query().After("gorm:query").Register(observe, func(tx *gorm.DB) {
		var want int
		switch tx.Statement.Dest.(type) {
		case *[]LandingLibraryTemplate:
			want = 10
			sourceBatches = append(sourceBatches, tx.RowsAffected)
		case *[]LandingLibraryFavorite:
			want = 100
			favoriteBatches = append(favoriteBatches, tx.RowsAffected)
		default:
			return
		}
		limit, ok := tx.Statement.Clauses["LIMIT"].Expression.(clause.Limit)
		if !ok || limit.Limit == nil || *limit.Limit != want || tx.RowsAffected > int64(want) {
			t.Errorf("unbounded migration query for %s: rows=%d limit=%+v", tx.Statement.Table, tx.RowsAffected, limit)
		}
	}); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = s.DB.Callback().Query().Remove(observe) })
	const fault = "test:landing-cover-migration-failure"
	inserted := 0
	if err := s.DB.Callback().Create().Before("gorm:create").Register(fault, func(tx *gorm.DB) {
		if _, ok := tx.Statement.Dest.(*LandingCover); ok {
			inserted++
			if inserted == 13 {
				tx.AddError(errors.New("simulated second-batch cover write failure"))
			}
		}
	}); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = s.DB.Callback().Create().Remove(fault) })
	if err := s.DB.Transaction(migrateLandingCovers); err == nil {
		t.Fatal("mid-migration write failure was ignored")
	}
	if err := s.DB.Callback().Create().Remove(fault); err != nil {
		t.Fatal(err)
	}
	var updated int64
	if err := s.DB.Model(&LandingLibraryTemplate{}).Where("cover_hash <> ?", "").Count(&updated).Error; err != nil || updated != 0 || countRows(t, s, &LandingCover{}) != 0 {
		t.Fatal("a failed batch migration left partially committed cover jobs or references")
	}
	sourceBatches, favoriteBatches = nil, nil
	for range 2 {
		if err := s.DB.Transaction(migrateLandingCovers); err != nil {
			t.Fatal(err)
		}
	}
	if len(sourceBatches) != 6 || sourceBatches[5] != 1 || len(favoriteBatches) != 2 || favoriteBatches[0] != 100 || favoriteBatches[1] != 1 {
		t.Fatalf("unexpected migration batches: sources=%v favorites=%v", sourceBatches, favoriteBatches)
	}
	if countRows(t, s, &LandingCover{}) != 51 || countRows(t, s, &LandingCoverSnapshot{}) != 101 {
		t.Fatal("batched migration skipped or duplicated a catalog or collected snapshot")
	}
	for revisionID, hash := range expected {
		var snapshot LandingCoverSnapshot
		if err := s.DB.First(&snapshot, "revision_id = ?", revisionID).Error; err != nil || snapshot.CoverHash != hash {
			t.Fatalf("composite-key batch boundary skipped saved revision %s", revisionID)
		}
	}
}

